"""Pydantic models for the gold-standard evaluation set."""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field, field_validator


class EvalQuestion(BaseModel):
    """One row in a question set.

    `expected_sources` and `expected_contains` are both optional — leave
    either out if you don't want to score that dimension.
    """

    question: str = Field(min_length=1, max_length=4000)
    expected_sources: list[str] = Field(default_factory=list)
    expected_relevance: dict[str, float] = Field(default_factory=dict)
    expected_contains: list[str] = Field(default_factory=list)
    accepted_refusals: list[str] = Field(default_factory=list)
    # A correct answer in plain words. Only the LLM judge reads it (to score
    # correctness); the keyword and source checks do not need it.
    reference_answer: str = Field(default="", max_length=8000)
    # Where the question came from: written by a person, generated by the chat
    # model from one chunk, or saved from a conversation you had.
    origin: Literal["manual", "synthetic", "conversation"] = "manual"
    # A draft is a generated question nobody has read yet. Drafts are kept in
    # the set but never scored: a model that writes its own exam and then sits
    # it proves little until a person has checked the questions.
    status: Literal["accepted", "draft"] = "accepted"
    # For generated questions: the chunk the question was written from, so a
    # reviewer can open the passage and check the question against it.
    source_chunk_id: str = ""

    @field_validator("question")
    @classmethod
    def _not_blank(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("question must not be blank")
        return value.strip()
